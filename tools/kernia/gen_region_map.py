"""Generate Kernia's stand-in region map, in place of Hoenn's.

    python3 tools/kernia/gen_region_map.py [preview.png]

Writes graphics/pokenav/region_map/map.bin (the tilemap), src/data/region_map/region_map_layout.h
(which map section each grid cell is), and the Kernia sections' x/y/width/height in
src/data/region_map/region_map_sections.json (where the player's icon sits).

It's a placeholder until the real map is drawn (design/CustomArt.md): a blocky Cornwall built
from Hoenn's plain sea, land, route and town tiles, with no coastline or new art. The grid is
28x15 cells, one 8x8 tile each, drawn at tile (x + 1, y + 2).
"""
import json, os, re, sys

REPO = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
W, H = 28, 15
GRID_X, GRID_Y = 1, 2           # MAPCURSOR_X_MIN, MAPCURSOR_Y_MIN in src/region_map.c.
TILEMAP_W = 64                  # map.bin is a 64x64 affine tilemap, one byte per tile.

SEA, LAND, MOOR, ROUTE, TOWN = 0, 51, 6, 12, 13   # Tiles in graphics/pokenav/region_map/map.png.

# Cornwall, west to east: the land on each row, as (first x, last x).
LAND_ROWS = {4: (17, 23), 5: (13, 25), 6: (9, 26), 7: (6, 26), 8: (3, 25), 9: (2, 24),
             10: (3, 21), 11: (5, 17), 12: (10, 13)}
MOOR_CELLS = [(14, 6), (15, 6), (16, 6), (14, 7), (15, 7), (16, 7), (17, 7)]   # Bodmin Moor.

# Kernia's places: section, cells, and the tile drawn there. Towns are one cell; routes run
# between them. Balwyn is in the far west, Route 1 runs east to Carnrudh, Carn Kowr is the
# hill north of it, and Route 2 heads south and then west towards Porthliw.
PLACES = [
    ('MAPSEC_BALWYN', [(3, 9)], TOWN),
    ('MAPSEC_KERNIA_ROUTE_1', [(4, 9), (5, 9), (6, 9)], ROUTE),
    ('MAPSEC_CARNRUDH', [(7, 9)], TOWN),
    ('MAPSEC_CARN_KOWR', [(7, 8)], MOOR),
    ('MAPSEC_KERNIA_ROUTE_2', [(7, 10), (6, 10)], ROUTE),
    ('MAPSEC_PORTHLIW', [(5, 10)], TOWN),
]


def build():
    tiles = [[SEA] * W for _ in range(H)]
    for y, (x0, x1) in LAND_ROWS.items():
        for x in range(x0, x1 + 1):
            tiles[y][x] = LAND
    for (x, y) in MOOR_CELLS:
        tiles[y][x] = MOOR
    sections = [['MAPSEC_NONE'] * W for _ in range(H)]
    for mapsec, cells, tile in PLACES:
        for (x, y) in cells:
            tiles[y][x] = tile
            sections[y][x] = mapsec
    return tiles, sections


def write_tilemap(tiles):
    tm = bytearray(TILEMAP_W * TILEMAP_W)
    for y in range(H):
        for x in range(W):
            tm[(y + GRID_Y) * TILEMAP_W + x + GRID_X] = tiles[y][x]
    open(os.path.join(REPO, 'graphics', 'pokenav', 'region_map', 'map.bin'), 'wb').write(bytes(tm))
    return tm


def write_layout(sections):
    lines = ['// Generated by tools/kernia/gen_region_map.py: Kernia\'s stand-in region map grid.',
             'static const mapsec_u8_t sRegionMap_MapSectionLayout[MAP_HEIGHT][MAP_WIDTH] = {']
    lines += ['    {' + ', '.join(row) + '},' for row in sections]
    lines.append('};')
    open(os.path.join(REPO, 'src', 'data', 'region_map', 'region_map_layout.h'), 'w').write('\n'.join(lines) + '\n')


def write_section_positions():
    """Set each Kernia section's bounding box, keeping the JSON's own formatting."""
    path = os.path.join(REPO, 'src', 'data', 'region_map', 'region_map_sections.json')
    s = open(path).read()
    for mapsec, cells, _ in PLACES:
        xs, ys = [c[0] for c in cells], [c[1] for c in cells]
        box = '"x": %d,\n      "y": %d,\n      "width": %d,\n      "height": %d' % (
            min(xs), min(ys), max(xs) - min(xs) + 1, max(ys) - min(ys) + 1)
        entry = re.compile(r'("id": "%s",\n      "name": "[^"]*")(,\n      "x": \d+,\n      "y": \d+,\n      "width": \d+,\n      "height": \d+)?' % mapsec)
        s, n = entry.subn(lambda m: m.group(1) + ',\n      ' + box, s)
        assert n == 1, mapsec
    open(path, 'w').write(s)


if __name__ == '__main__':
    tiles, sections = build()
    tm = write_tilemap(tiles)
    write_layout(sections)
    write_section_positions()
    if len(sys.argv) > 1:
        sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
        from gbarender import read_png_indexed, write_png
        g = os.path.join(REPO, 'graphics', 'pokenav', 'region_map')
        w, h, px = read_png_indexed(os.path.join(g, 'map.png'))
        pal = [tuple(int(v) for v in l.split()) for l in open(os.path.join(g, 'map.pal')).read().split('\n')[3:] if l.strip()]
        rows = []
        for ty in range(20):
            for r in range(8):
                row = []
                for tx in range(32):
                    t = tm[ty * TILEMAP_W + tx]
                    for c in px[(t // (w // 8)) * 8 + r][(t % (w // 8)) * 8:(t % (w // 8)) * 8 + 8]:
                        row += list(pal[c - 112] if c >= 112 else pal[0]) * 3
                for _ in range(3):
                    rows.append(row)
        write_png(sys.argv[1], 32 * 8 * 3, 20 * 8 * 3, rows)
